#!/usr/bin/env python3
"""Makes the five notepad covers for lists from cover-source.png and writes them into
patch/files/ListCoverImages.h (and a preview, Cover-Varianten.png, next to this script).

Usage: python3 tools/cover/make_covers.py     (needs Pillow: pip install pillow)
"""
import io
from pathlib import Path

from PIL import Image, ImageDraw

HERE = Path(__file__).resolve().parent
OUT_HEADER = HERE.parent.parent / "patch" / "files" / "ListCoverImages.h"
src = Image.open(HERE / 'cover-source.png').convert('L')
# clean paper: light gray paper texture -> white; keep pen strokes and the dotted lines
src = src.point(lambda v: 255 if v > 222 else v)
# no rounded corner on the cover: paint the top-right corner as paper
d = ImageDraw.Draw(src); d.rectangle((740, 0, 799, 60), fill=255)
# a straight right edge (the source has a dark rim there)
d.rectangle((792, 0, 799, 1332), fill=255)
W = 800; HDR = 152; P = 115
rows = [src.crop((0, HDR + i*P, W, HDR + (i+1)*P)) for i in range(9)]   # 0-4 items, 5-8 empty
checked0 = rows[0].crop((88, 0, 178, P)); unchecked = rows[1].crop((88, 0, 178, P))
header = src.crop((0, 0, W, HDR))
variants = [([0,1,2,3,4],[1,0,0,1,0]), ([2,4,1],[0,1,0]), ([3,0,4,2],[1,1,0,0]),
            ([4,2,0,1,3],[0,0,1,1,0]), ([0,3],[1,0])]
TH = 1333  # 3:5, the shape CrossPoint gives every cover thumbnail (width = 0.6 x height)
# Where the reader writes the list name on a cover (480x800 pixels): the old heading's place.
TITLE_BOX = (118, 16, 470, 90)


def compose(order, chk, heading=True):
    c = Image.new('L', (W, TH), 255)
    c.paste(header, (0, 0)); y = HDR
    if not heading:  # blank the handwritten "To Do List", keep hole, strip and margin line
        ImageDraw.Draw(c).rectangle((192, 25, 790, HDR - 12), fill=255)
    for idx, ck in zip(order, chk):
        r = rows[idx].copy(); r.paste(checked0 if ck else unchecked, (88, 0)); c.paste(r, (0, y)); y += P
    e = 5
    while y < TH:
        c.paste(rows[5 + (e - 5) % 4], (0, y)); y += P; e += 1
    dc = ImageDraw.Draw(c)
    for ly in range(HDR, TH, P):          # ruled lines again, clearer than in the photo-like source
        for x in range(60, W - 8, 8):
            dc.rectangle((x, ly - 1, x + 3, ly + 1), fill=40)
    return c.resize((480, 800), Image.LANCZOS)


def packbits(data):
    """PackBits run-length coding (as in TIFF); ListCover.h unpacks it."""
    out = bytearray(); i = 0; n = len(data)
    while i < n:
        run = 1
        while i + run < n and run < 128 and data[i + run] == data[i]:
            run += 1
        if run >= 2:
            out += bytes([(257 - run) & 0xFF, data[i]]); i += run
            continue
        start = i
        while i < n and i - start < 128 and not (i + 1 < n and data[i + 1] == data[i]):
            i += 1
        out += bytes([i - start - 1]) + data[start:i]
    return bytes(out)


outs = []
bmps = []   # generic covers (with "To Do List"): PNG, shown until a list has its own cover
bases = []  # covers without heading, 1-bit 480x800 packed: the reader writes the list name on them
for n, (order, chk) in enumerate(variants, 1):
    # Grayscale PNG (16 levels): CrossPoint scales it to each thumbnail size and dithers it itself,
    # so the whole page always shows (a BMP would be shown 1:1 and cut off).
    small = compose(order, chk).point(lambda v: round(v * 15 / 255) * 17)
    buf = io.BytesIO(); small.save(buf, format='PNG', optimize=True); bmps.append(buf.getvalue())
    bw = compose(order, chk, heading=False).convert('1')  # Floyd-Steinberg, as e-ink shows it
    raw = bw.tobytes()   # rows of 60 bytes, MSB first, 1 = white
    bases.append(packbits(raw))
    preview = bw.convert('L'); d = ImageDraw.Draw(preview)
    d.rectangle(TITLE_BOX, outline=0)
    outs.append(preview.resize((300, 500), Image.LANCZOS))
sheet = Image.new('L', (300*5 + 40, 500), 128)
for i, o in enumerate(outs): sheet.paste(o, (i*310, 0))
sheet.save(HERE / 'Cover-Varianten.png')

lines = ['#pragma once', '// Notepad covers for lists (added by the Crosspoint-ToDoList patch).',
         '// Generated by tools/cover/make_covers.py: five 480x800 grayscale PNGs, one is picked per list,\n'
         '// and the same pages without heading, for covers with the list name.',
         '// "inline" keeps a single copy in the firmware however many files include this.', '',
         '#include <cstddef>', '#include <cstdint>', '', '#include "ListPath.h"', '', 'namespace todolist {', '']
for n, b in enumerate(bmps, 1):
    lines.append(f'inline constexpr uint8_t kCover{n}[{len(b)}] = {{')
    for i in range(0, len(b), 20):
        lines.append('    ' + ', '.join(f'0x{x:02X}' for x in b[i:i + 20]) + ',')
    lines.append('};')
for n, b in enumerate(bases, 1):
    lines.append(f'inline constexpr uint8_t kCoverBase{n}[{len(b)}] = {{')
    for i in range(0, len(b), 20):
        lines.append('    ' + ', '.join(f'0x{x:02X}' for x in b[i:i + 20]) + ',')
    lines.append('};')
lines += ['', f'// Where the list name goes on a cover (x0, y0, x1, y1 in the 480x800 picture).',
          f'constexpr int kTitleBox[4] = {{{TITLE_BOX[0]}, {TITLE_BOX[1]}, {TITLE_BOX[2]}, {TITLE_BOX[3]}}};']
lines += ['', 'struct CoverImage {', '  const uint8_t* data;', '  size_t size;', '};',
          'inline const CoverImage& coverImage(const int i) {', '  static const CoverImage covers[kCoverCount] = {']
lines += [f'      {{kCover{n}, sizeof(kCover{n})}},' for n in range(1, len(bmps) + 1)]
lines += ['  };', '  return covers[((i % kCoverCount) + kCoverCount) % kCoverCount];', '}', '',
          '// The same pages without heading, 1-bit 480x800 (rows of 60 bytes, 1 = white), PackBits packed.',
          'inline const CoverImage& coverBase(const int i) {', '  static const CoverImage bases[kCoverCount] = {']
lines += [f'      {{kCoverBase{n}, sizeof(kCoverBase{n})}},' for n in range(1, len(bases) + 1)]
lines += ['  };', '  return bases[((i % kCoverCount) + kCoverCount) % kCoverCount];', '}', '',
          '}  // namespace todolist', '']
OUT_HEADER.write_text('\n'.join(lines))
print(f"wrote {OUT_HEADER.name} with {len(bmps)} covers")
